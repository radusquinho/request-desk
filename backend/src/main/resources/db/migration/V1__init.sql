CREATE TABLE work_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type          VARCHAR(20)   NOT NULL,
    requester     VARCHAR(50)   NOT NULL,
    title         VARCHAR(200)  NOT NULL,
    amount        NUMERIC(12, 2),
    start_date    DATE,
    end_date      DATE,
    status        VARCHAR(20)   NOT NULL,
    reason        VARCHAR(500)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    review_due_at TIMESTAMP WITH TIME ZONE,
    decided_at    TIMESTAMP WITH TIME ZONE,
    decided_by    VARCHAR(50)
);

CREATE INDEX idx_work_request_status ON work_request (status);
CREATE INDEX idx_work_request_requester ON work_request (requester);

CREATE TABLE audit_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT        NOT NULL REFERENCES work_request (id),
    action     VARCHAR(40)   NOT NULL,
    actor      VARCHAR(50)   NOT NULL,
    detail     VARCHAR(500)  NOT NULL,
    at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_event_request ON audit_event (request_id);

CREATE TABLE outbox_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type      VARCHAR(40)   NOT NULL,
    request_id      BIGINT        NOT NULL REFERENCES work_request (id),
    payload         VARCHAR(4000) NOT NULL,
    state           VARCHAR(20)   NOT NULL,
    attempts        INT           NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at    TIMESTAMP WITH TIME ZONE,
    last_error      VARCHAR(500)
);

CREATE INDEX idx_outbox_due ON outbox_message (state, next_attempt_at);
